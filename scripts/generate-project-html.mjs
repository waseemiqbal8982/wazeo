#!/usr/bin/env node
/**
 * Wazeo — project.html generator. Emits a single self-contained, secret-free
 * `<!> at the repo root. Reads package.json, TASKS.md, .env.example (names
 * only) and the memory ledger (.wazeo-memory).
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const MEM = path.join(ROOT, ".wazeo-memory");
const OUT = path.join(ROOT, "project.html");

function readJson(p) {
  try {
    return JSON.parse(fs.readFileSync(p, "utf8"));
  } catch {
    return null;
  }
}
function read(p) {
  try {
    return fs.readFileSync(p, "utf8");
  } catch {
    return "";
  }
}
function linesOf(p) {
  return read(p).split(/\r?\n/).filter(Boolean);
}
function parseChecklist(p) {
  const done = [], pending = [];
  for (const l of linesOf(p)) {
    if (/^\s*-\s*\[x\]/i.test(l)) done.push(l.replace(/^\s*-\s*\[x\]\s*/i, ""));
    else if (/^\s*-\s*\[ \]/.test(l)) pending.push(l.replace(/^\s*-\s*\[ \]\s*/, ""));
  }
  return { done, pending };
}
function esc(s) {
  return String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

const tasks = parseChecklist(path.join(ROOT, "TASKS.md"));
const envExample = read(path.join(ROOT, ".env.example"));
const envNames = (envExample.match(/^[A-Z][A-Z0-9_]+/gm) || []).filter(Boolean);
const pkg = readJson(path.join(ROOT, "package.json")) || {};
const state = readJson(path.join(MEM, "STATE.json")) || {};
let history = [];
try {
  history = fs
    .readFileSync(path.join(MEM, "HISTORY.jsonl"), "utf8")
    .split("\n")
    .filter(Boolean)
    .slice(-12)
    .map((l) => {
      try {
        return JSON.parse(l);
      } catch {
        return null;
      }
    })
    .filter(Boolean);
} catch {}

const doneHtml = tasks.done.slice(0, 80).map((t) => "<li>" + esc(t) + "</li>").join("");
const pendingHtml = tasks.pending.slice(0, 80).map((t) => "<li>" + esc(t) + "</li>").join("");

const sections = [];
sections.push(`<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Wazeo — Project Memory</title>
<style>
 body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;max-width:960px;margin:24px auto;padding:0 16px;color:#111;line-height:1.5}
 h1,h2{border-bottom:1px solid #ddd;padding-bottom:6px}
 code{background:#f0f0f0;padding:1px 4px;border-radius:4px;font-size:13px}
 table{border-collapse:collapse;width:100%;font-size:13px}
 th,td{border:1px solid #ddd;padding:6px 8px;text-align:left;vertical-align:top}
 th{background:#f6f6f6}
 .s{color:#777;font-size:12px}
 .ok{color:#0a7d35}.warn{color:#b26a00}.bad{color:#c0392b}
</style>
</head>
<body>
<h1>🧠 Wazeo — Project Memory</h1>
<p class="s">Auto-generated by <code>scripts/generate-project-html.mjs</code>. Read this FIRST before editing anything.</p>`);
sections.push(`<h2>1. Overview</h2>
<p>Wazeo is a premium SMM panel (Instagram / TikTok / YouTube) built with <b>Next.js 16 (App Router)</b> + TypeScript + Tailwind v4 + Supabase + Framer Motion + Chart.js. Supports gradual/organic delivery, admin panel, access keys, multi-language (en/ur/hi/fr/zh), themes, currency switching.</p>`);
sections.push(`<h2>2. Architecture</h2>
<ul>
 <li><b>Frontend:</b> app/ components/ (App Router; server + client components; shared ui/)</li>
 <li><b>Backend:</b> app/api/** route handlers (Node); server actions</li>
 <li><b>Data:</b> Supabase (Postgres) — all tables have RLS; service-role client server-only</li>
 <li><b>Auth:</b> Supabase Auth (email/password, OTP, access-key redeem); admin allowlist ADMIN_EMAILS; admin PIN</li>
 <li><b>Delivery engine:</b> lib/organic/ (curve → micro-step plan); lib/schedule.ts; cron /api/cron/process</li>
 <li><b>External:</b> SMM provider (provider.ts, mock fallback); Mercury AI (lib/ai.ts, fallback)</li>
 <li><b>Deploy:</b> Vercel (production https://innvera.shop) + GitHub Actions cron</li>
</ul>`);
sections.push(`<h2>3. Status</h2><p>Purpose: production. Complete state in <code>STATUS.md</code>, <code>TASKS.md</code> and the memory ledger (section 9).</p>`);
sections.push("<h2>4. Completed features</h2>" + (doneHtml ? "<ul>" + doneHtml + "</ul>" : "<p class='s'>none parsed</p>"));
sections.push("<h2>5. Pending tasks</h2>" + (pendingHtml ? "<ul>" + pendingHtml + "</ul>" : "<p class='s'>none parsed</p>"));
const envHtml = envNames.map((n) => "<tr><td><code>" + esc(n) + "</code></td><td>See <code>.env.example</code> / <code>docs/ENV_CHECKLIST.md</code></td></tr>").join("");
sections.push("<h2>6. Environment variables (names only — never values)</h2><table><tr><th>Variable</th><th>Note</th></tr>" + envHtml + "</table>");

sections.push(`<h2>7. Integrations &amp; configuration status</h2>
<table>
 <tr><th>Area</th><th>Status</th></tr>
 <tr><td>Supabase (URL/anon/service-role/DB)</td><td class="ok">Configured; RLS ON (all tables)</td></tr>
 <tr><td>Vercel deploy</td><td class="ok">Production https://innvera.shop · Node 24.x</td></tr>
 <tr><td>SMM Provider</td><td>Not configured → <b>Mock mode</b> active</td></tr>
 <tr><td>Mercury AI</td><td>Not configured → fallback/disabled</td></tr>
 <tr><td>Cron worker</td><td>GitHub Actions + /api/cron/process (CRON_SECRET)</td></tr>
</table>`);

sections.push(`<h2>8. Known issues</h2>
<ul>
 <li class="bad">[open] Access-key redemption: production /api/auth/* POST routes previously returned HTTP 405 (route handlers missing from deployed build). Local build includes all routes; root cause under investigation (Vercel deploy pipeline). Login / Supabase Auth confirmed working.</li>
 <li>Admin <code>tsx</code>-based test scripts need <code>npm i -D tsx</code> (dep missing in this check-out).</li>
</ul>`);

const histHtml = history.map((e) => "<tr><td class='s'>" + esc(e.ts || "") + "</td><td>" + esc(e.type || "") + "</td><td>" + esc(e.actor || "") + "</td><td>" + esc(e.message || "") + "</td></tr>").join("");
sections.push("<h2>9. Recent history (memory ledger tail)</h2><table><tr><th>time</th><th>type</th><th>actor</th><th>message</th></tr>" + histHtml + "</table>");

sections.push(`<h2>10. AI handover instructions</h2>
<ol>
 <li>Read this file (<code>project.html</code>) completely.</li>
 <li>Read <code>STATUS.md</code>, <code>TASKS.md</code>, <code>FEATURES.md</code>.</li>
 <li>Run <code>node scripts/memory.mjs status</code> and <code>list --last 50</code>.</li>
 <li>Inspect <code>package.json</code>, <code>next.config.ts</code>, <code>app/</code>, <code>lib/</code>, <code>supabase/</code>.</li>
 <li>Run <code>npm run lint</code> and <code>npm run build</code> before/after changes.</li>
 <li>Record decisions: <code>node scripts/memory.mjs log --type decision --message "..."</code>.</li>
</ol>`);

sections.push(`<script id="project-data" type="application/json">${JSON.stringify({
  project: "wazeo",
  stack: { next: pkg.dependencies?.next, react: pkg.dependencies?.react, supabase: pkg.dependencies?.["@supabase/supabase-js"] },
  envNames,
  status: "active",
  memory: { state, history: history.map((e) => ({ ts: e.ts, type: e.type, message: e.message })) },
})}</script>
</body>
</html>`);

const html = sections.join("\n");
fs.writeFileSync(OUT, html);
process.stdout.write(JSON.stringify({ ok: true, out: OUT, bytes: Buffer.byteLength(html) }, null, 2) + "\n");
